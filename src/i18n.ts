function detect(): "tr" | "en" {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale || "tr";
    return loc.toLowerCase().startsWith("tr") ? "tr" : "en";
  } catch {
    return "tr";
  }
}

